//! A local, offline copy of the CTF platform's `challenge-kit`, vendored into a scaffolded
//! challenge by the ORRESS Challenge Workbench so you can build and test the challenge without
//! the private platform repository.
//!
//! It mirrors the public API the platform exposes — [`Challenge`], [`Verdict`], [`assigned_id`]
//! and [`run`] — so your `main.rs` compiles and runs here exactly as it will on the platform.
//! When you submit, the platform rebuilds your `check()` against *its* kit, which injects the
//! real per-player flag and the real challenge id. This local copy never sees or sets a flag.
//!
//! Do not edit this file: the Workbench overwrites it, and the platform ignores it on submit.

use std::io::{BufRead, Write};

/// The result your [`Challenge::check`] returns for one attempt.
pub enum Verdict {
    /// The input is correct. On the platform this reveals the player's personal flag; the
    /// message is shown alongside it.
    Accept(String),
    /// The input is wrong. The message is shown to the player as feedback.
    Reject(String),
}

/// A challenge: its metadata, and the `check()` that decides whether an input is correct.
pub trait Challenge {
    /// The challenge id. Return [`assigned_id`]; the platform fills it in at build time.
    fn id(&self) -> &str;
    /// The title shown to the player.
    fn title(&self) -> &str;
    /// A one- or two-line description of the puzzle.
    fn brief(&self) -> &str;
    /// The label for the input box (for example "Password" or "Flag").
    fn input_label(&self) -> &str;
    /// Decide whether `input` is correct.
    fn check(&mut self, input: &str) -> Verdict;
}

/// The challenge id. The platform assigns it at build time (through the `CTF_CHALLENGE_ID`
/// environment variable; `CHALLENGE_ID` is also accepted); locally it is a fixed placeholder so the
/// project builds and runs.
pub fn assigned_id() -> &'static str {
    option_env!("CTF_CHALLENGE_ID")
        .or(option_env!("CHALLENGE_ID"))
        .unwrap_or("local-dev")
}

// --- per-user seed (for "protection seed" / keygen-me challenges) ---------
//
// Mirrors the platform kit so a seeded challenge behaves locally as it will on the platform: the
// seed is read from the `ORRESS_SEED` env var (hex) or a `seed.bin` next to the executable, with a
// fixed "unseeded" fallback. The platform injects a real per-player `seed.bin` into each download.

/// Where the resolved [`seed`] came from.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum SeedSource {
    /// The `ORRESS_SEED` environment variable (hex) — handy for scripted testing.
    Env,
    /// A `seed.bin` next to the executable — the normal per-user download.
    File,
    /// No seed available: the fixed fallback (its flags are rejected by the site).
    Unseeded,
}

/// The fallback used when no `ORRESS_SEED` / `seed.bin` is present.
const UNSEEDED: &[u8] = b"UNSEEDED";

fn resolved_seed() -> &'static (Vec<u8>, SeedSource) {
    static SEED: std::sync::OnceLock<(Vec<u8>, SeedSource)> = std::sync::OnceLock::new();
    SEED.get_or_init(|| {
        if let Ok(h) = std::env::var("ORRESS_SEED") {
            if let Some(b) = decode_hex(&h) {
                if !b.is_empty() {
                    return (b, SeedSource::Env);
                }
            }
        }
        if let Ok(exe) = std::env::current_exe() {
            if let Some(dir) = exe.parent() {
                if let Ok(b) = std::fs::read(dir.join("seed.bin")) {
                    if !b.is_empty() {
                        return (b, SeedSource::File);
                    }
                }
            }
        }
        (UNSEEDED.to_vec(), SeedSource::Unseeded)
    })
}

/// This download's per-user seed (resolved once per process).
pub fn seed() -> Vec<u8> {
    resolved_seed().0.clone()
}

/// Where [`seed`] came from.
pub fn seed_source() -> SeedSource {
    resolved_seed().1
}

/// A per-user "account name" for keygen-me challenges — `AGENT-` plus the first three seed bytes as
/// uppercase hex. The platform derives it identically, so the serial a player computes for the name
/// shown here is exactly the one the platform expects (and is useless to any other player).
pub fn seed_name() -> String {
    let s = seed();
    let hx: String = s.iter().take(3).map(|b| format!("{b:02X}")).collect();
    format!("AGENT-{hx}")
}

fn decode_hex(s: &str) -> Option<Vec<u8>> {
    let s = s.trim();
    if s.is_empty() || s.len() % 2 != 0 || !s.is_ascii() {
        return None;
    }
    (0..s.len())
        .step_by(2)
        .map(|i| u8::from_str_radix(&s[i..i + 2], 16).ok())
        .collect()
}

/// Runs the challenge as a simple console session for local testing: prints the brief, then
/// reads attempts until one is accepted (or input ends). The platform wraps the very same
/// [`Challenge`] in its own runner, so what you test here is what players will face.
pub fn run(mut challenge: impl Challenge) -> std::io::Result<()> {
    let stdin = std::io::stdin();
    println!("=== {} ===", challenge.title());
    println!("{}", challenge.brief());
    println!("(local test — challenge id: {})", assigned_id());
    loop {
        print!("{}: ", challenge.input_label());
        std::io::stdout().flush()?;
        let mut line = String::new();
        if stdin.lock().read_line(&mut line)? == 0 {
            println!();
            return Ok(()); // end of input
        }
        let input = line.trim_end_matches(['\r', '\n']);
        match challenge.check(input) {
            Verdict::Accept(msg) => {
                println!("[accepted] {msg}");
                println!("On the platform this would reveal your flag.");
                return Ok(());
            }
            Verdict::Reject(msg) => println!("[rejected] {msg}"),
        }
    }
}
