//! The Dalvik opcode table: each opcode's mnemonic, instruction format and the kind of constant-
//! pool reference it carries (if any). The decoder in `lib.rs` uses this to walk a method's code.
//! Instructions are measured in 16-bit code units; every format's size is fixed, so decoding stays
//! aligned even across opcodes ORRESS doesn't render in detail.

/// A Dalvik instruction format (named as in the Dalvik spec: `AABBCC`-style).
#[derive(Clone, Copy, PartialEq, Eq)]
pub enum Fmt {
    F10x,
    F12x,
    F11n,
    F11x,
    F10t,
    F20t,
    F22x,
    F21t,
    F21s,
    F21h,
    /// `const-wide/high16`: like 21h, but the literal is the top 16 bits of a 64-bit value.
    F21hw,
    F21c,
    F23x,
    F22b,
    F22t,
    F22s,
    F22c,
    F30t,
    F31t,
    F31i,
    F31c,
    F32x,
    F35c,
    F3rc,
    F51l,
    F45cc,
    F4rcc,
    /// Unused/unknown opcode (decoded as one unit so we stay aligned).
    Unknown,
}

impl Fmt {
    /// Size of this format in 16-bit code units.
    pub fn units(self) -> usize {
        use Fmt::*;
        match self {
            F10x | F12x | F11n | F11x | F10t => 1,
            F20t | F22x | F21t | F21s | F21h | F21hw | F21c | F23x | F22b | F22t | F22s | F22c => 2,
            F30t | F31t | F31i | F31c | F32x | F35c | F3rc => 3,
            F45cc | F4rcc => 4,
            F51l => 5,
            Unknown => 1,
        }
    }
}

/// What a referencing instruction's index points at.
#[derive(Clone, Copy, PartialEq, Eq)]
pub enum Ref {
    None,
    Str,
    Type,
    Field,
    Method,
    /// Call site / method handle / prototype — rendered as a raw index.
    Other,
}

/// `(mnemonic, format, reference kind)` for a Dalvik opcode.
pub fn info(op: u8) -> (&'static str, Fmt, Ref) {
    use Fmt::*;
    use Ref::{Field as RF, Method as RM, Str as RS, Type as RT};
    let n = Ref::None;
    match op {
        0x00 => ("nop", F10x, n),
        0x01 => ("move", F12x, n),
        0x02 => ("move/from16", F22x, n),
        0x03 => ("move/16", F32x, n),
        0x04 => ("move-wide", F12x, n),
        0x05 => ("move-wide/from16", F22x, n),
        0x06 => ("move-wide/16", F32x, n),
        0x07 => ("move-object", F12x, n),
        0x08 => ("move-object/from16", F22x, n),
        0x09 => ("move-object/16", F32x, n),
        0x0a => ("move-result", F11x, n),
        0x0b => ("move-result-wide", F11x, n),
        0x0c => ("move-result-object", F11x, n),
        0x0d => ("move-exception", F11x, n),
        0x0e => ("return-void", F10x, n),
        0x0f => ("return", F11x, n),
        0x10 => ("return-wide", F11x, n),
        0x11 => ("return-object", F11x, n),
        0x12 => ("const/4", F11n, n),
        0x13 => ("const/16", F21s, n),
        0x14 => ("const", F31i, n),
        0x15 => ("const/high16", F21h, n),
        0x16 => ("const-wide/16", F21s, n),
        0x17 => ("const-wide/32", F31i, n),
        0x18 => ("const-wide", F51l, n),
        0x19 => ("const-wide/high16", F21hw, n),
        0x1a => ("const-string", F21c, RS),
        0x1b => ("const-string/jumbo", F31c, RS),
        0x1c => ("const-class", F21c, RT),
        0x1d => ("monitor-enter", F11x, n),
        0x1e => ("monitor-exit", F11x, n),
        0x1f => ("check-cast", F21c, RT),
        0x20 => ("instance-of", F22c, RT),
        0x21 => ("array-length", F12x, n),
        0x22 => ("new-instance", F21c, RT),
        0x23 => ("new-array", F22c, RT),
        0x24 => ("filled-new-array", F35c, RT),
        0x25 => ("filled-new-array/range", F3rc, RT),
        0x26 => ("fill-array-data", F31t, n),
        0x27 => ("throw", F11x, n),
        0x28 => ("goto", F10t, n),
        0x29 => ("goto/16", F20t, n),
        0x2a => ("goto/32", F30t, n),
        0x2b => ("packed-switch", F31t, n),
        0x2c => ("sparse-switch", F31t, n),
        0x2d => ("cmpl-float", F23x, n),
        0x2e => ("cmpg-float", F23x, n),
        0x2f => ("cmpl-double", F23x, n),
        0x30 => ("cmpg-double", F23x, n),
        0x31 => ("cmp-long", F23x, n),
        0x32 => ("if-eq", F22t, n),
        0x33 => ("if-ne", F22t, n),
        0x34 => ("if-lt", F22t, n),
        0x35 => ("if-ge", F22t, n),
        0x36 => ("if-gt", F22t, n),
        0x37 => ("if-le", F22t, n),
        0x38 => ("if-eqz", F21t, n),
        0x39 => ("if-nez", F21t, n),
        0x3a => ("if-ltz", F21t, n),
        0x3b => ("if-gez", F21t, n),
        0x3c => ("if-gtz", F21t, n),
        0x3d => ("if-lez", F21t, n),
        0x44 => ("aget", F23x, n),
        0x45 => ("aget-wide", F23x, n),
        0x46 => ("aget-object", F23x, n),
        0x47 => ("aget-boolean", F23x, n),
        0x48 => ("aget-byte", F23x, n),
        0x49 => ("aget-char", F23x, n),
        0x4a => ("aget-short", F23x, n),
        0x4b => ("aput", F23x, n),
        0x4c => ("aput-wide", F23x, n),
        0x4d => ("aput-object", F23x, n),
        0x4e => ("aput-boolean", F23x, n),
        0x4f => ("aput-byte", F23x, n),
        0x50 => ("aput-char", F23x, n),
        0x51 => ("aput-short", F23x, n),
        0x52 => ("iget", F22c, RF),
        0x53 => ("iget-wide", F22c, RF),
        0x54 => ("iget-object", F22c, RF),
        0x55 => ("iget-boolean", F22c, RF),
        0x56 => ("iget-byte", F22c, RF),
        0x57 => ("iget-char", F22c, RF),
        0x58 => ("iget-short", F22c, RF),
        0x59 => ("iput", F22c, RF),
        0x5a => ("iput-wide", F22c, RF),
        0x5b => ("iput-object", F22c, RF),
        0x5c => ("iput-boolean", F22c, RF),
        0x5d => ("iput-byte", F22c, RF),
        0x5e => ("iput-char", F22c, RF),
        0x5f => ("iput-short", F22c, RF),
        0x60 => ("sget", F21c, RF),
        0x61 => ("sget-wide", F21c, RF),
        0x62 => ("sget-object", F21c, RF),
        0x63 => ("sget-boolean", F21c, RF),
        0x64 => ("sget-byte", F21c, RF),
        0x65 => ("sget-char", F21c, RF),
        0x66 => ("sget-short", F21c, RF),
        0x67 => ("sput", F21c, RF),
        0x68 => ("sput-wide", F21c, RF),
        0x69 => ("sput-object", F21c, RF),
        0x6a => ("sput-boolean", F21c, RF),
        0x6b => ("sput-byte", F21c, RF),
        0x6c => ("sput-char", F21c, RF),
        0x6d => ("sput-short", F21c, RF),
        0x6e => ("invoke-virtual", F35c, RM),
        0x6f => ("invoke-super", F35c, RM),
        0x70 => ("invoke-direct", F35c, RM),
        0x71 => ("invoke-static", F35c, RM),
        0x72 => ("invoke-interface", F35c, RM),
        0x74 => ("invoke-virtual/range", F3rc, RM),
        0x75 => ("invoke-super/range", F3rc, RM),
        0x76 => ("invoke-direct/range", F3rc, RM),
        0x77 => ("invoke-static/range", F3rc, RM),
        0x78 => ("invoke-interface/range", F3rc, RM),
        0x7b => ("neg-int", F12x, n),
        0x7c => ("not-int", F12x, n),
        0x7d => ("neg-long", F12x, n),
        0x7e => ("not-long", F12x, n),
        0x7f => ("neg-float", F12x, n),
        0x80 => ("neg-double", F12x, n),
        0x81 => ("int-to-long", F12x, n),
        0x82 => ("int-to-float", F12x, n),
        0x83 => ("int-to-double", F12x, n),
        0x84 => ("long-to-int", F12x, n),
        0x85 => ("long-to-float", F12x, n),
        0x86 => ("long-to-double", F12x, n),
        0x87 => ("float-to-int", F12x, n),
        0x88 => ("float-to-long", F12x, n),
        0x89 => ("float-to-double", F12x, n),
        0x8a => ("double-to-int", F12x, n),
        0x8b => ("double-to-long", F12x, n),
        0x8c => ("double-to-float", F12x, n),
        0x8d => ("int-to-byte", F12x, n),
        0x8e => ("int-to-char", F12x, n),
        0x8f => ("int-to-short", F12x, n),
        0x90..=0xaf => (binop_23x(op), F23x, n),
        0xb0..=0xcf => (binop_2addr(op), F12x, n),
        0xd0 => ("add-int/lit16", F22s, n),
        0xd1 => ("rsub-int", F22s, n),
        0xd2 => ("mul-int/lit16", F22s, n),
        0xd3 => ("div-int/lit16", F22s, n),
        0xd4 => ("rem-int/lit16", F22s, n),
        0xd5 => ("and-int/lit16", F22s, n),
        0xd6 => ("or-int/lit16", F22s, n),
        0xd7 => ("xor-int/lit16", F22s, n),
        0xd8 => ("add-int/lit8", F22b, n),
        0xd9 => ("rsub-int/lit8", F22b, n),
        0xda => ("mul-int/lit8", F22b, n),
        0xdb => ("div-int/lit8", F22b, n),
        0xdc => ("rem-int/lit8", F22b, n),
        0xdd => ("and-int/lit8", F22b, n),
        0xde => ("or-int/lit8", F22b, n),
        0xdf => ("xor-int/lit8", F22b, n),
        0xe0 => ("shl-int/lit8", F22b, n),
        0xe1 => ("shr-int/lit8", F22b, n),
        0xe2 => ("ushr-int/lit8", F22b, n),
        0xfa => ("invoke-polymorphic", F45cc, RM),
        0xfb => ("invoke-polymorphic/range", F4rcc, RM),
        0xfc => ("invoke-custom", F35c, Ref::Other),
        0xfd => ("invoke-custom/range", F3rc, Ref::Other),
        0xfe => ("const-method-handle", F21c, Ref::Other),
        0xff => ("const-method-type", F21c, Ref::Other),
        _ => ("unused", Unknown, n),
    }
}

fn binop_23x(op: u8) -> &'static str {
    const OPS: [&str; 32] = [
        "add-int",
        "sub-int",
        "mul-int",
        "div-int",
        "rem-int",
        "and-int",
        "or-int",
        "xor-int",
        "shl-int",
        "shr-int",
        "ushr-int",
        "add-long",
        "sub-long",
        "mul-long",
        "div-long",
        "rem-long",
        "and-long",
        "or-long",
        "xor-long",
        "shl-long",
        "shr-long",
        "ushr-long",
        "add-float",
        "sub-float",
        "mul-float",
        "div-float",
        "rem-float",
        "add-double",
        "sub-double",
        "mul-double",
        "div-double",
        "rem-double",
    ];
    OPS[(op - 0x90) as usize]
}

